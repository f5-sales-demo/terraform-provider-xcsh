func TestInsertSectionBeforeOnce(t *testing.T) {
	t.Parallel()

	input := "# Resource\n\n## Import\n\nImport details.\n"
	section := "## Common Types\n\nShared definitions.\n"
	want := "# Resource\n\n## Common Types\n\nShared definitions.\n\n## Import\n\nImport details.\n"

	got := InsertSectionBeforeOnce(input, "## Common Types", section, "## Import")
	if got != want {
		t.Fatalf("unexpected inserted section:\nwant:\n%s\ngot:\n%s", want, got)
	}
	if again := InsertSectionBeforeOnce(got, "## Common Types", section, "## Import"); again != got {
		t.Fatal("section insertion is not idempotent")
	}
}

