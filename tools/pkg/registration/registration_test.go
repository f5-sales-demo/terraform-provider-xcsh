func TestCleanOrphanGeneratedFilesRemovesOnlyStaleMutableSurface(t *testing.T) {
	outDir := t.TempDir()
	clntDir := t.TempDir()
	header := []byte("// Code generated by generate-all-schemas.go. DO NOT EDIT.\npackage generated\n")
	for _, path := range []string{
		filepath.Join(outDir, "read_only_resource.go"),
		filepath.Join(outDir, "read_only_data_source.go"),
		filepath.Join(clntDir, "read_only_types.go"),
	} {
		if err := os.WriteFile(path, header, 0o600); err != nil {
			t.Fatal(err)
		}
	}

	CleanOrphanGeneratedFiles(outDir, clntDir, map[string]GeneratedFileSet{
		"read_only": {DataSource: true, Client: true},
	})

	if _, err := os.Stat(filepath.Join(outDir, "read_only_resource.go")); !os.IsNotExist(err) {
		t.Fatalf("stale mutable resource was not removed: %v", err)
	}
	for _, path := range []string{
		filepath.Join(outDir, "read_only_data_source.go"),
		filepath.Join(clntDir, "read_only_types.go"),
	} {
		if _, err := os.Stat(path); err != nil {
			t.Fatalf("read-only generated surface was removed: %s: %v", filepath.Base(path), err)
		}
	}
}

func TestGenerateProviderRegistration(t *testing.T) {
	outDir := t.TempDir()

	results := []openapi.GenerationResult{
		{ResourceName: "http_loadbalancer", Success: true, AttrCount: 5, BlockCount: 2},
		{ResourceName: "origin_pool", Success: true, AttrCount: 3, BlockCount: 1},
		{ResourceName: "failed_resource", Success: false, Error: "something went wrong"},
	}

	GenerateProviderRegistration(results, outDir)

	providerPath := filepath.Join(outDir, "provider.go")
	content, err := os.ReadFile(providerPath)
	if err != nil {
		t.Fatalf("provider.go was not created: %v", err)
	}

	contentStr := string(content)

	// Should contain the DO NOT EDIT header
	if !contains(contentStr, "DO NOT EDIT") {
		t.Error("expected DO NOT EDIT header in provider.go")
	}

	// Should contain resource registrations for successful resources
	// naming.ToResourceTypeName: "http_loadbalancer" -> "HTTPLoadBalancer"
	if !contains(contentStr, "NewHTTPLoadBalancerResource") {
		t.Error("expected NewHTTPLoadBalancerResource in provider.go")
	}
	if !contains(contentStr, "NewOriginPoolResource") {
		t.Error("expected NewOriginPoolResource in provider.go")
	}

	// Should contain data source registrations
	if !contains(contentStr, "NewHTTPLoadBalancerDataSource") {
		t.Error("expected NewHTTPLoadBalancerDataSource in provider.go")
	}

	// Should NOT contain failed resource
	if contains(contentStr, "NewFailedResourceResource") {
		t.Error("did not expect NewFailedResourceResource in provider.go")
	}
}

// Hand-written standalone data sources have no generated companion, so the
// only thing wiring them into the provider is StandaloneDataSources. If an
// entry is missing, the data source is silently absent from the released
// provider; if an entry does not match its Go constructor, provider.go stops
// compiling. Both are guarded here.
func TestGenerateProviderRegistration_StandaloneDataSources(t *testing.T) {
	outDir := t.TempDir()

	GenerateProviderRegistration(nil, outDir)

	content, err := os.ReadFile(filepath.Join(outDir, "provider.go"))
	if err != nil {
		t.Fatalf("provider.go was not created: %v", err)
	}
	contentStr := string(content)

	// repoRoot is three levels up from tools/pkg/registration.
	repoRoot := filepath.Join("..", "..", "..")

	for _, ds := range StandaloneDataSources {
		ctor := "New" + naming.ToResourceTypeName(ds) + "DataSource,"
		if !contains(contentStr, ctor) {
			t.Errorf("standalone data source %q: expected %s in provider.go DataSources()", ds, ctor)
		}

		implPath := filepath.Join(repoRoot, "internal", "provider", ds+"_data_source.go")
		impl, err := os.ReadFile(implPath) //nolint:gosec // fixed path derived from the allowlist
		if err != nil {
			t.Errorf("standalone data source %q: no hand-written implementation at %s: %v", ds, implPath, err)
			continue
		}
		if !contains(string(impl), "func New"+naming.ToResourceTypeName(ds)+"DataSource(") {
			t.Errorf("standalone data source %q: %s does not define New%sDataSource — provider.go would not compile",
				ds, implPath, naming.ToResourceTypeName(ds))
		}
		// Standalone files are hand-written and must never carry the
		// generated-file header, or CleanOrphanGeneratedFiles deletes them.
		if contains(string(impl), "DO NOT EDIT") {
			t.Errorf("standalone data source %q: %s carries a DO NOT EDIT header and would be pruned as an orphan", ds, implPath)
		}
	}

	// xcsh_site_registration resolves a CE's runtime registration name and is
	// required by the registration-approval workflow.
	if !contains(contentStr, "NewSiteRegistrationDataSource,") {
		t.Error("expected NewSiteRegistrationDataSource in provider.go DataSources()")
	}
}

func TestGenerateProviderRegistration_ActionResource(t *testing.T) {
	outDir := t.TempDir()

	// An action-style resource (x-f5xc-action) has a generated resource but no
	// generated data source companion. It must register as a resource only.
	results := []openapi.GenerationResult{
		{ResourceName: "registration_approval", Success: true, IsReadOnly: false, IsAction: true},
	}

	GenerateProviderRegistration(results, outDir)

	content, err := os.ReadFile(filepath.Join(outDir, "provider.go"))
	if err != nil {
		t.Fatalf("provider.go was not created: %v", err)
	}
	contentStr := string(content)

	// naming.ToResourceTypeName: "registration_approval" -> "RegistrationApproval"
	if !contains(contentStr, "NewRegistrationApprovalResource,") {
		t.Error("expected NewRegistrationApprovalResource in provider.go for action resource")
	}
	if contains(contentStr, "NewRegistrationApprovalDataSource,") {
		t.Error("action resource must NOT register a data source, but found NewRegistrationApprovalDataSource")
	}
}

func TestGenerateProviderRegistration_ReadOnlyDataSource(t *testing.T) {
	outDir := t.TempDir()

	// A read-only result is data-source-only: no resource, but it MUST still
	// register a data source. The action guard must not regress this.
	results := []openapi.GenerationResult{
		{ResourceName: "flow_anomaly", Success: true, IsReadOnly: true, IsAction: false},
	}

	GenerateProviderRegistration(results, outDir)

	content, err := os.ReadFile(filepath.Join(outDir, "provider.go"))
	if err != nil {
		t.Fatalf("provider.go was not created: %v", err)
	}
	contentStr := string(content)

	if !contains(contentStr, "NewFlowAnomalyDataSource,") {
		t.Error("expected read-only result to register NewFlowAnomalyDataSource")
	}
	if contains(contentStr, "NewFlowAnomalyResource,") {
		t.Error("read-only result must NOT register a resource, but found NewFlowAnomalyResource")
	}
}

func TestGenerateProviderRegistration_FirstClassAction(t *testing.T) {
	outDir := t.TempDir()
	GenerateProviderRegistration([]openapi.GenerationResult{{
		ResourceName: "site_upgrade_sw", Success: true, IsTerraformAction: true, IsResponseOperation: true,
	}}, outDir)
	content, err := os.ReadFile(filepath.Join(outDir, "provider.go"))
	if err != nil {
		t.Fatal(err)
	}
	source := string(content)
	for _, want := range []string{"provider.ProviderWithActions", "resp.ActionData = c", "func (p *XCSHProvider) Actions", "NewSiteUpgradeSwAction,"} {
		if !contains(source, want) {
			t.Errorf("provider registration missing %q", want)
		}
	}
	for _, forbidden := range []string{"NewSiteUpgradeSwResource,", "NewSiteUpgradeSwDataSource,"} {
		if contains(source, forbidden) {
			t.Errorf("provider registration unexpectedly contains %q", forbidden)
		}
	}
}

