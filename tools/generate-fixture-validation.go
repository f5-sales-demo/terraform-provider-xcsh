package main

import (
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	files, err := filepath.Glob("internal/provider/*_test.go")
	if err != nil {
		panic(err)
	}
	fixtures := map[string]*ast.FuncDecl{}
	tests := map[string]*ast.FuncDecl{}
	functions := map[string]*ast.FuncDecl{}
	for _, path := range files {
		f, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
		if err != nil {
			panic(err)
		}
		if f.Name.Name != "provider_test" {
			continue
		}
		for _, decl := range f.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || fn.Recv != nil {
				continue
			}
			functions[fn.Name.Name] = fn
			if strings.HasPrefix(fn.Name.Name, "TestAcc") {
				tests[fn.Name.Name] = fn
			}
			if strings.HasPrefix(fn.Name.Name, "testAcc") && fn.Type.Results != nil && len(fn.Type.Results.List) == 1 {
				if typ, ok := fn.Type.Results.List[0].Type.(*ast.Ident); ok && typ.Name == "string" {
					fixtures[fn.Name.Name] = fn
				}
			}
		}
	}
	names := keys(fixtures)
	var out strings.Builder
	out.WriteString("// Code generated by tools/generate-fixture-validation.go. DO NOT EDIT.\npackage provider_test\nimport \"github.com/f5-sales-demo/terraform-provider-xcsh/internal/acctest\"\nfunc init(){\n")
	for _, name := range names {
		args := []string{}
		for _, field := range fixtures[name].Type.Params.List {
			value := ""
			switch typ := field.Type.(type) {
			case *ast.Ident:
				switch typ.Name {
				case "string":
					value = "\"tf-acc-test-fixture\""
				case "int", "int64", "uint", "uint64":
					value = "1"
				case "bool":
					value = "false"
				default:
					panic(fmt.Sprintf("fixture %s: unknown argument %s", name, typ.Name))
				}
			case *ast.StarExpr:
				value = "&acctest.TestCertificates{}"
			case *ast.MapType:
				value = "map[string]string{\"environment\":\"test\"}"
			case *ast.ArrayType:
				value = "[]string{\"example.com\"}"
			default:
				panic(fmt.Sprintf("fixture %s parameter %T", name, field.Type))
			}
			for range field.Names {
				args = append(args, value)
			}
		}
		fmt.Fprintf(&out, "acctest.RegisterFixture(%q,func() string{return %s(%s)})\n", name, name, strings.Join(args, ","))
	}
	var resolve func(string, map[string]bool, map[string]bool)
	resolve = func(name string, seen, found map[string]bool) {
		if seen[name] {
			return
		}
		seen[name] = true
		if _, ok := fixtures[name]; ok {
			found[name] = true
			return
		}
		fn, ok := functions[name]
		if !ok || fn.Body == nil {
			return
		}
		ast.Inspect(fn.Body, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)
			if ok {
				if ident, ok := call.Fun.(*ast.Ident); ok {
					resolve(ident.Name, seen, found)
				}
			}
			return true
		})
	}
	for _, name := range keys(tests) {
		found := map[string]bool{}
		resolve(name, map[string]bool{}, found)
		fmt.Fprintf(&out, "acctest.RegisterTestFixtures(%q,[]string{", name)
		for _, fixture := range keys(found) {
			fmt.Fprintf(&out, "%q,", fixture)
		}
		out.WriteString("})\n")
	}
	out.WriteString("}\n")
	data, err := format.Source([]byte(out.String()))
	if err != nil {
		panic(err)
	}
	if err = os.WriteFile("internal/provider/acceptance_fixtures_generated_test.go", data, 0644); err != nil {
		panic(err)
	}
	fmt.Println("Generated", len(fixtures), "fixtures and", len(tests), "test mappings")
}
func keys[T any](m map[string]T) []string {
	out := []string{}
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
